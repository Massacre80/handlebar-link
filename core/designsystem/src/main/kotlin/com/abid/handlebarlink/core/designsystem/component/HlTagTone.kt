package com.abid.handlebarlink.core.designsystem.component

/** The colour of an [HlTag]. */
public enum class HlTagTone {
    /** Brand: "SOON", or running and starting (the CarPlay tab's Connected and Connecting). */
    BRAND,

    /** Danger: something only the rider can fix (the CarPlay tab's Needs you). */
    DANGER,

    /** Muted: a quiet state (Ready, Not set up, Stopped). */
    QUIET,
}
